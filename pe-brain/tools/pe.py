def cmd_size(a):
    src = Path(a.inputs)
    raw = read(src)
    t = tables(raw)
    policy = {r.get("key", ""): r for r in t.get("Policy", [])}
    comps = t.get("Components", [])
    gaps, synthetic = [], "SYNTHETIC" in raw.upper()
    cols = ["cpu_cores", "ram_gb", "disk_gb_fixed"]
    rows, tot = [], dict(cpu=0.0, ram=0.0, net=0.0, disk=0.0, day=0.0)
    for r in comps:
        name = r.get("component", "?")
        qty = num(r.get("qty", ""))
        if qty is None:
            gaps.append(f"{name}: qty unknown")
            continue
        if qty == 0:
            continue
        if unknown(r.get("source", "")):
            gaps.append(f"{name}: no source")
        vals = {}
        for c in cols:
            vals[c] = num(r.get(c, ""))
            if vals[c] is None:
                gaps.append(f"{name}: {c} unknown")
        net = num(r.get("net_mbps", ""))
        if net is None:
            pk, hz = num(r.get("payload_kb", "")), num(r.get("rate_hz", ""))
            net = pk * hz * 0.008 if pk is not None and hz is not None else None
        if net is None:
            gaps.append(f"{name}: net_mbps or payload_kb and rate_hz unknown")
        st = r.get("store_gb_day", "").strip().lower()
        day = (net * 10.8 if net is not None else None) if st == "stream" else num(st)
        if day is None:
            gaps.append(f"{name}: store_gb_day unknown")
        def mul(v):
            return v * qty if v is not None else None
        row = dict(name=name, qty=qty, cpu=mul(vals["cpu_cores"]), ram=mul(vals["ram_gb"]),
                   net=mul(net), disk=mul(vals["disk_gb_fixed"]), day=mul(day), src=r.get("source", ""))
        rows.append(row)
        for k in tot:
            if row[k] is not None:
                tot[k] += row[k]
    ret = policy.get("retention_days", {})
    ret_v = num(ret.get("value", ""))
    if ret_v is None:
        gaps.append("policy retention_days unknown")
    elif unknown(ret.get("source", "")):
        gaps.append("policy retention_days has no source")
    hr = policy.get("headroom_pct", {})
    hr_v = num(hr.get("value", ""))
    hr_ok = hr_v is not None and not unknown(hr.get("source", ""))
    if not hr_ok:
        gaps.append("policy headroom_pct missing or unsourced; totals shown without headroom")
    storage = tot["disk"] + tot["day"] * (ret_v or 0)
    factor = 1 + hr_v / 100 if hr_ok else 1.0
    status = "INCOMPLETE" if gaps else "COMPLETE"

    def f(v, d=1):
        return "?" if v is None else f"{v:,.{d}f}"
    out = [f"# Sizing result: {src.name}", "",
           f"Generated by `tools/pe.py size` on {date.today().isoformat()}. Do not edit; fix the inputs and re-run. Method: `knowledge/sizing/size-method.md`.", "",
           f"**Status: {status}**" + ("  **SYNTHETIC inputs: NOT FOR ISSUE**" if synthetic else ""), "",
           "## Totals", "",
           "| quantity | raw | with headroom |", "|---|---|---|",
           f"| CPU cores | {f(tot['cpu'])} | {f(tot['cpu'] * factor)} |",
           f"| RAM GB | {f(tot['ram'])} | {f(tot['ram'] * factor)} |",
           f"| Network Mbps | {f(tot['net'], 2)} | {f(tot['net'] * factor, 2)} |",
           f"| Storage GB ({f(ret_v, 0)} days retention) | {f(storage)} | {f(storage * factor)} |",
           f"| Daily stored GB | {f(tot['day'], 2)} | {f(tot['day'] * factor, 2)} |", "",
           f"Headroom applied: {f(hr_v, 0) + '%' if hr_ok else 'none (unsourced)'}.", "",
           "## Per component", "",
           "| component | qty | cpu | ram GB | Mbps | disk GB | GB/day | source |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['name']} | {f(r['qty'], 0)} | {f(r['cpu'])} | {f(r['ram'])} | {f(r['net'], 2)} | {f(r['disk'])} | {f(r['day'], 2)} | {r['src']} |")
    out += ["", "## Gaps", ""] + ([f"- {g}" for g in gaps] or ["None."])
    text = "\n".join(out) + "\n"
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8")
        print(f"wrote {a.out}")
    print(text)
    return 0


# ---------- status, new-project, sources ----------

def cmd_status(a):
    d = ROOT / "projects" / a.slug
    if not d.exists():
        print(f"No project '{a.slug}'. Create it: python3 tools/pe.py new-project {a.slug}")
        return 1
    work = d / "work"
    print(f"Project status: {a.slug}\n")
    for wf, stages in WORKFLOWS.items():
        cells_ = []
        for s in stages:
            hit = sorted(work.glob(f"{wf}-{s}*.md")) if work.exists() else []
            cells_.append(f"[{wf}-{s}] {'COMPLETE' if hit else 'PENDING'}")
        print("  " + "  -->  ".join(cells_))
    extra = [p.name for p in sorted(work.glob("*.md"))
             if not any(p.name.startswith(w + "-") for w in WORKFLOWS)] if work.exists() else []
    if extra:
        print("\n  other work files: " + ", ".join(extra))
    ev = [p for p in (d / "evidence").glob("*") if p.name != ".gitkeep"] if (d / "evidence").exists() else []
    print(f"\n  evidence files: {len(ev)}")
    return 0


def cmd_new_project(a):
    slug = a.slug
    if not re.match(r"^[a-z0-9]+(-[a-z0-9]+)*$", slug):
        print("Slug must be lowercase-with-hyphens.")
        return 1
    d = ROOT / "projects" / slug
    if d.exists():
        print(f"projects/{slug} already exists; not touched.")
        return 1
    shutil.copytree(ROOT / "_templates" / "project", d)
    rec = d / "record.md"
    rec.write_text(read(rec).replace("SLUG", slug).replace("YEAR", str(date.today().year)), encoding="utf-8")
    print(f"created projects/{slug}/ (record.md, evidence/, work/). Fill record.md, then run: python3 tools/pe.py index")
    return 0


def cmd_sources(_):
    rows = tables(read(ROOT / "_system/sources.md")).get("Stone Three repositories (Azure DevOps)", [])
    for r in rows:
        name, path = r.get("name", ""), os.path.expanduser(r.get("expected local path", ""))
        p = (ROOT / path) if not os.path.isabs(path) else Path(path)
        if not p.exists():
            print(f"MISSING  {name}: expected at {path}")
            continue
        try:
            head = subprocess.run(["git", "-C", str(p), "log", "-1", "--format=%h %cs"],
                                  capture_output=True, text=True).stdout.strip()
        except OSError:
            head = "?"
        skills = len(list(p.rglob("SKILL.md")))
        mds = len(list(p.rglob("*.md")))
        print(f"PRESENT  {name}: {p}  last commit {head or 'n/a'}  {mds} md files, {skills} SKILL.md")
    return 0


