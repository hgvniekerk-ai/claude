# ---------- parsing helpers ----------

def read(path):
    return Path(path).read_text(encoding="utf-8")


def frontmatter(text):
    """Parse the YAML subset used in PE Brain: scalars, inline lists, block lists."""
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---", 4)
    if end == -1:
        return None, text
    block, body = text[4:end], text[end + 4:].lstrip("\n")
    data, key = {}, None
    for raw in block.splitlines():
        line = strip_comment(raw)
        if not line.strip():
            continue
        if line.lstrip().startswith("- ") and key:
            data.setdefault(key, [])
            if isinstance(data[key], list):
                data[key].append(unquote(line.lstrip()[2:].strip()))
            continue
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if val.startswith("[") and val.endswith("]"):
            inner = val[1:-1].strip()
            data[key] = [unquote(v.strip()) for v in inner.split(",") if v.strip()] if inner else []
        elif val == "":
            data[key] = []
        else:
            data[key] = unquote(val)
    for k, v in data.items():
        if v == [] and k not in ("sources", "tags", "products"):
            data[k] = ""
    return data, body


def strip_comment(line):
    out, q = [], None
    for ch in line:
        if ch in "\"'":
            q = None if q == ch else (q or ch)
        if ch == "#" and q is None and (not out or out[-1] == " "):
            break
        out.append(ch)
    return "".join(out).rstrip()


def unquote(v):
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


def tables(text):
    """Return {heading: [row dicts]} for the first table under each ## heading."""
    result, heading, lines = {}, None, text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("## "):
            heading = line[3:].strip()
        elif heading and line.strip().startswith("|") and heading not in result:
            if i + 1 < len(lines) and re.match(r"^\s*\|[\s:|-]+\|\s*$", lines[i + 1]):
                header = cells(line)
                rows, j = [], i + 2
                while j < len(lines) and lines[j].strip().startswith("|"):
                    vals = cells(lines[j])
                    rows.append({h.lower(): (vals[k] if k < len(vals) else "") for k, h in enumerate(header)})
                    j += 1
                result[heading] = rows
                i = j
                continue
        i += 1
    return result


def cells(line):
    parts = line.strip().strip("|").split("|")
    return [p.strip().strip("`").strip() for p in parts]


def unknown(v):
    return v is None or v.strip() == "" or bool(TBC.search(v)) or v.strip().upper() == "TBC"


def num(v):
    try:
        return float(v.replace(",", "").strip())
    except (ValueError, AttributeError):
        return None


def md_files():
    for p in sorted(ROOT.rglob("*.md")):
        rel = p.relative_to(ROOT).as_posix()
        if rel.startswith(".git/") or "/evidence/" in rel or rel.startswith(".claude/skills/s3-"):
            continue
        yield p, rel


def knowledge_notes():
    for p, rel in md_files():
        if rel.startswith("knowledge/") and p.name not in ("CONTEXT.md", "INDEX.md"):
            yield p, rel


def project_records():
    for p in sorted((ROOT / "projects").glob("*/record.md")):
        yield p, p.relative_to(ROOT).as_posix()


# ---------- index ----------

def build_indexes():
    k = [GEN_BANNER, "# Knowledge index", "",
         "| id | title | domain | type | authority | owner | reviewed | path |",
         "|---|---|---|---|---|---|---|---|"]
    for p, rel in knowledge_notes():
        fm, _ = frontmatter(read(p))
        fm = fm or {}
        k.append("| {} | {} | {} | {} | {} | {} | {} | `{}` |".format(
            fm.get("id", ""), fm.get("title", ""), fm.get("domain", ""), fm.get("type", ""),
            fm.get("authority", ""), fm.get("owner", ""), fm.get("reviewed", "") or "never",
            rel[len("knowledge/"):]))
    pr = [GEN_BANNER, "# Project index", "",
          "| slug | site_alias | status | year | pe | products | tags |",
          "|---|---|---|---|---|---|---|"]
    for p, rel in project_records():
        fm, _ = frontmatter(read(p))
        fm = fm or {}
        pr.append("| [{0}]({0}/record.md) | {1} | {2} | {3} | {4} | {5} | {6} |".format(
            fm.get("slug", p.parent.name), fm.get("site_alias", ""), fm.get("status", ""),
            fm.get("year", ""), fm.get("pe", ""), ", ".join(fm.get("products", []) or []),
            ", ".join(fm.get("tags", []) or [])))
    return {"knowledge/INDEX.md": "\n".join(k) + "\n", "projects/INDEX.md": "\n".join(pr) + "\n"}


def cmd_index(_):
    for rel, text in build_indexes().items():
        (ROOT / rel).write_text(text, encoding="utf-8")
        print("wrote", rel)


# ---------- check ----------

def registered_versions():
    path = ROOT / "knowledge/products/versions.md"
    if not path.exists():
        return set()
    rows = tables(read(path)).get("Product and tag version register", [])
    rows = rows or next(iter(tables(read(path)).values()), [])
    return {"{}@{}".format(r.get("product", ""), r.get("version", "")) for r in rows
            if not unknown(r.get("product", ""))}


def cmd_check(_):
    errors, warns, tbc_total, ids = [], [], 0, {}
    versions = registered_versions()
    for p, rel in md_files():
        text = read(p)
        lines = text.count("\n") + 1
        if EM_DASH in text:
            errors.append(f"{rel}: contains an em dash")
        tbc_total += len(TBC.findall(text))
        if p.name == "CONTEXT.md" and lines > 80:
            errors.append(f"{rel}: CONTEXT.md is {lines} lines (limit 80)")
        if rel.startswith("knowledge/") and p.name not in ("CONTEXT.md", "INDEX.md") and lines > 200:
            warns.append(f"{rel}: {lines} lines (limit 200, split it)")
        for target in re.findall(r"\]\(([^)\s]+)\)", text):
            if target.startswith(("http", "#", "mailto:")):
                continue
            if not (p.parent / target.split("#")[0]).exists():
                errors.append(f"{rel}: broken link {target}")
        for target in re.findall(r"`([\w./-]+\.(?:md|py|sh))`", text):
            if "/" not in target or target.startswith(("work/", "_core/")):
                continue
            if not ((ROOT / target).exists() or (p.parent / target).exists()):
                warns.append(f"{rel}: path not found `{target}`")
    for p, rel in knowledge_notes():
        fm, _ = frontmatter(read(p))
        if fm is None:
            errors.append(f"{rel}: no frontmatter")
            continue
        for field in ("id", "title", "domain", "type", "authority", "owner", "sources"):
            if not fm.get(field):
                errors.append(f"{rel}: missing {field}")
        if fm.get("domain") and fm["domain"] not in DOMAINS:
            errors.append(f"{rel}: domain '{fm['domain']}' not in {sorted(DOMAINS)}")
        if fm.get("domain") and not rel.startswith(f"knowledge/{fm['domain']}/"):
            errors.append(f"{rel}: domain '{fm['domain']}' does not match folder")
        if fm.get("type") and fm["type"] not in NOTE_TYPES:
            errors.append(f"{rel}: type '{fm['type']}' not in {sorted(NOTE_TYPES)}")
        if fm.get("authority") and fm["authority"] not in AUTHORITY:
            errors.append(f"{rel}: authority '{fm['authority']}' not in {sorted(AUTHORITY)}")
        if fm.get("id") in ids:
            errors.append(f"{rel}: duplicate id {fm['id']} (also {ids[fm['id']]})")
        ids[fm.get("id")] = rel
        if fm.get("authority") == "s3-verified" and not fm.get("reviewed"):
            errors.append(f"{rel}: s3-verified needs a reviewed date")
    for p, rel in project_records():
        fm, _ = frontmatter(read(p))
        if fm is None:
            errors.append(f"{rel}: no frontmatter")
            continue
        if fm.get("slug") != p.parent.name:
            errors.append(f"{rel}: slug '{fm.get('slug')}' does not match folder")
        if fm.get("status") not in PROJECT_STATUS:
            errors.append(f"{rel}: status '{fm.get('status')}' not in {sorted(PROJECT_STATUS)}")
        for prod in fm.get("products", []) or []:
            if prod not in versions:
                warns.append(f"{rel}: product '{prod}' not in knowledge/products/versions.md")
    for rel, text in build_indexes().items():
        f = ROOT / rel
        if not f.exists() or read(f) != text:
            errors.append(f"{rel}: stale or missing, run: python3 tools/pe.py index")
    for e in errors:
        print("ERROR  ", e)
    for w in warns:
        print("WARN   ", w)
    print(f"\n{len(errors)} errors, {len(warns)} warnings, {tbc_total} [TBC] markers open")
    return 1 if errors else 0


# ---------- find ----------

def cmd_find(a):
    terms = [t.lower() for t in a.terms]
    hits = []
    paths = [(p, rel) for p, rel in md_files()
             if rel.startswith(("knowledge/", "projects/")) and not rel.endswith("INDEX.md")
             and not p.name == "CONTEXT.md"]
    for p, rel in paths:
        text = read(p)
        fm, body = frontmatter(text)
        fm = fm or {}
        if a.domain and fm.get("domain") != a.domain:
            continue
        if a.tag and a.tag not in (fm.get("tags") or []):
            continue
        low = text.lower()
        head = " ".join(str(v) for v in fm.values()).lower()
        matched = [t for t in terms if t in low]
        if not matched:
            continue
        score = sum(low.count(t) for t in matched) + 3 * sum(head.count(t) for t in matched)
        score *= len(matched)
        lines = [(n + 1, l.strip()) for n, l in enumerate(text.splitlines())
                 if any(t in l.lower() for t in terms)][:3]
        hits.append((score, len(matched), rel, fm.get("authority", fm.get("type", "")), lines))
    hits.sort(key=lambda h: (-h[1], -h[0]))
    if not hits:
        print("No matches. History holds nothing on: " + " ".join(a.terms))
        return 0
    for score, n, rel, auth, lines in hits[:a.limit]:
        print(f"{rel}  [{auth}]  terms {n}/{len(terms)}  score {score}")
        for ln, l in lines:
            print(f"    {ln}: {l[:140]}")
    return 0


# ---------- netcheck ----------

def parse_ports(v):
    out = []
    for part in v.replace(" ", "").split(","):
        if not part:
            continue
        lo, _, hi = part.partition("-")
        lo_n, hi_n = num(lo), num(hi or lo)
        if lo_n is None or hi_n is None or not (0 < lo_n <= hi_n <= 65535):
            return None
        out.append((int(lo_n), int(hi_n)))
    return out


def cmd_netcheck(a):
    src = Path(a.register)
    t = tables(read(src))
    zones, hosts, flows = t.get("Zones", []), t.get("Hosts", []), t.get("Flows", [])
    E, W, tbc = [], [], len(TBC.findall(read(src)))
    znet = {}
    for i, z in enumerate(zones, 1):
        name = z.get("zone", "")
        if unknown(name):
            E.append(f"Zones row {i}: zone name missing")
            continue
        if unknown(z.get("source", "")):
            W.append(f"Zone {name}: no source")
        if unknown(z.get("subnet", "")):
            W.append(f"Zone {name}: subnet unknown")
            continue
        try:
            net = ipaddress.ip_network(z["subnet"], strict=True)
        except ValueError as ex:
            E.append(f"Zone {name}: subnet '{z['subnet']}' invalid ({ex})")
            continue
        znet[name] = net
        gw = z.get("gateway", "")
        if not unknown(gw):
            try:
                g = ipaddress.ip_address(gw)
                if g not in net or g in (net.network_address, net.broadcast_address):
                    E.append(f"Zone {name}: gateway {gw} is not a usable address in {net}")
            except ValueError:
                E.append(f"Zone {name}: gateway '{gw}' invalid")
        if unknown(z.get("firewall_owner", "")):
            W.append(f"Zone {name}: firewall owner not named")
    names = list(znet)
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            if znet[names[i]].overlaps(znet[names[j]]):
                E.append(f"Zones {names[i]} ({znet[names[i]]}) and {names[j]} ({znet[names[j]]}) overlap")
    vlans = {}
    for z in zones:
        v = z.get("vlan", "")
        if not unknown(v):
            if v in vlans:
                E.append(f"VLAN {v} used by zones {vlans[v]} and {z.get('zone')}")
            vlans[v] = z.get("zone")
    seen_ip, seen_host, host_zone = {}, set(), {}
    gateways = {z.get("gateway") for z in zones}
    for h in hosts:
        hn = h.get("hostname", "")
        if unknown(hn):
            E.append("Hosts: a row has no hostname")
            continue
        if hn.lower() in seen_host:
            E.append(f"Host {hn}: duplicate hostname")
        seen_host.add(hn.lower())
        zone = h.get("zone", "")
        host_zone[hn] = zone
        if unknown(h.get("source", "")):
            W.append(f"Host {hn}: no source")
        if zone not in [z.get("zone") for z in zones]:
            E.append(f"Host {hn}: zone '{zone}' is not in the Zones table")
        ip = h.get("ip", "")
        if unknown(ip):
            W.append(f"Host {hn}: IP unknown")
        else:
            try:
                addr = ipaddress.ip_address(ip)
                if ip in seen_ip:
                    E.append(f"Host {hn}: IP {ip} already used by {seen_ip[ip]}")
                seen_ip[ip] = hn
                if ip in gateways:
                    E.append(f"Host {hn}: IP {ip} is a zone gateway")
                net = znet.get(zone)
                if net is not None:
                    if addr not in net:
                        E.append(f"Host {hn}: IP {ip} is outside zone {zone} ({net})")
                    elif net.num_addresses > 2 and addr in (net.network_address, net.broadcast_address):
                        E.append(f"Host {hn}: IP {ip} is the network or broadcast address of {net}")
            except ValueError:
                E.append(f"Host {hn}: IP '{ip}' invalid")
        ntp = h.get("ntp_source", "")
        if unknown(ntp):
            W.append(f"Host {hn}: no NTP source")
        elif not ntp.startswith("external:") and ntp not in [x.get("hostname") for x in hosts]:
            E.append(f"Host {hn}: NTP source '{ntp}' is not a host or external:<name>")
    zone_names = {z.get("zone") for z in zones}

    def zone_of(ep):
        if ep in host_zone:
            return host_zone[ep]
        if ep in zone_names:
            return ep
        if ep.startswith("external:"):
            return ep
        return None

    conduits = {}
    ntp_flows = set()
    for i, f in enumerate(flows, 1):
        fr, to = f.get("from", ""), f.get("to", "")
        label = f"Flow {i} ({fr} -> {to})"
        zf, zt = zone_of(fr), zone_of(to)
        if zf is None:
            E.append(f"{label}: '{fr}' is not a host, zone or external:<name>")
        if zt is None:
            E.append(f"{label}: '{to}' is not a host, zone or external:<name>")
        proto = f.get("protocol", "").upper()
        if proto not in ("TCP", "UDP", "ICMP", "ANY"):
            E.append(f"{label}: protocol '{f.get('protocol')}' not TCP, UDP, ICMP or ANY")
        port = f.get("port", "")
        if proto in ("TCP", "UDP"):
            if unknown(port):
                W.append(f"{label}: port unknown")
            else:
                pr = parse_ports(port)
                if pr is None:
                    E.append(f"{label}: port '{port}' invalid")
                elif sum(hi - lo + 1 for lo, hi in pr) > 1000:
                    W.append(f"{label}: opens {sum(hi - lo + 1 for lo, hi in pr)} ports; see knowledge/network/net-windows-ports.md")
                elif proto == "UDP" and any(lo <= 123 <= hi for lo, hi in pr):
                    ntp_flows.add((fr, to))
        if unknown(f.get("source", "")):
            W.append(f"{label}: no source")
        if zf and zt and zf != zt:
            conduits.setdefault((zf, zt), []).append(f"{proto} {port} {fr} -> {to}: {f.get('purpose', '')}")
    for h in hosts:
        ntp = h.get("ntp_source", "")
        hn = h.get("hostname", "")
        if unknown(ntp) or unknown(hn):
            continue
        za, zb = zone_of(hn), zone_of(ntp)
        if za and zb and za != zb:
            ok = any((fr in (hn, za)) and (to in (ntp, zb)) for fr, to in ntp_flows)
            if not ok:
                W.append(f"Host {hn}: NTP source {ntp} is in another zone but no UDP 123 flow covers it")
    result = "FAIL" if E else ("PASS WITH WARNINGS" if W else "PASS")
    out = [f"# Network register validation: {src.name}", "",
           f"Generated by `tools/pe.py netcheck` on {date.today().isoformat()}. Do not edit; fix the register and re-run.", "",
           f"**Result: {result}**  ({len(E)} errors, {len(W)} warnings, {tbc} [TBC] open)", "",
           f"Zones {len(zones)}, hosts {len(hosts)}, flows {len(flows)}.", "", "## Errors", ""]
    out += [f"- {e}" for e in E] or ["None."]
    out += ["", "## Warnings", ""] + ([f"- {w}" for w in W] or ["None."])
    out += ["", "## Conduit summary", "", "Cross-zone flows the firewall owners must allow.", ""]
    if conduits:
        for (zf, zt), items in sorted(conduits.items()):
            out.append(f"### {zf} -> {zt}")
            out += [f"- {x}" for x in items] + [""]
    else:
        out.append("No cross-zone flows.")
    text = "\n".join(out).rstrip() + "\n"
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8")
        print(f"wrote {a.out}")
    print(text)
    return 1 if E else 0


